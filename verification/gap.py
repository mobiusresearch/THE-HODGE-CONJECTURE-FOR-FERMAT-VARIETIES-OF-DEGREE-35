# ====================================================================== independent index computation (FLINT)
def flint_indices(m, generator_lists):
    """for each list of generators of a subgroup L of K_m of full rank: (product of the pivots of the Hermite
    normal form, product of the Smith invariants = [K_m : L])"""
    N = m - 1
    out = []
    for gens in generator_lists:
        entries = []
        for g in gens:
            row = [0] * N
            for y, c in g.items():
                row[y - 1] = c
            entries.extend(row)
        H = flint.fmpz_mat(len(gens), N, entries).hnf()
        Hl = [[int(v) for v in r] for r in H.tolist() if any(r)]
        piv = 1
        for r in Hl:
            piv *= next(v for v in r if v)
        Sm = flint.fmpz_mat(len(Hl), N, [v for r in Hl for v in r]).snf()
        prod = 1
        for i in range(len(Hl)):
            prod *= int(Sm[i, i])
        out.append((piv, abs(prod)))
    return out


