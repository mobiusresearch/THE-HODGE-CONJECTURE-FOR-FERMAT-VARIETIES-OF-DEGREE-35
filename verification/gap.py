def hodge_with_divisor(m, L):
    """All Hodge characters of level m with L entries (L = 4 or 6), up to order, having an entry equal to a
    divisor g < m of m.  Meet in the middle: a tuple is split as (g, x_1, ..., x_{L/2-1}) and
    (y_1 <= ... <= y_{L/2}).  The key sum_k 2 sum_i <t_k a_i> 2^(w k) (t_k the units < m/2) is exact, as
    each field is < 2^w, and a tuple is a Hodge character iff its key equals sum_k L m 2^(w k)."""
    T = half_units(m)
    h = L // 2
    w = (2 * L * m).bit_length() + 1
    P = [0] * m
    for y in range(1, m):
        v = 0
        for k, t in enumerate(T):
            v |= (2 * ((t * y) % m)) << (w * k)
        P[y] = v
    target = sum((L * m) << (w * k) for k in range(len(T)))
    left = {}
    for g in divisors(m)[:-1]:
        for xs in combinations_with_replacement(range(1, m), h - 1):
            left.setdefault(P[g] + sum(P[x] for x in xs), []).append((g,) + xs)
    listed = set()
    for ys in combinations_with_replacement(range(1, m), h - 1):
        base = target - sum(P[y] for y in ys)
        last0 = ys[-1] if ys else 1
        for z in range(last0, m):
            for lt in left.get(base - P[z], ()):
                listed.add(tuple(sorted(lt + ys + (z,))))
    return listed


