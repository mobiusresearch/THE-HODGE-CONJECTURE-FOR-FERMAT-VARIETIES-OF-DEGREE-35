# ====================================================================== arithmetic
def units(m):
    return [t for t in range(1, m) if gcd(t, m) == 1]


def half_units(m):
    """one unit from each pair {t, -t}"""
    return [t for t in units(m) if 2 * t < m] if m > 2 else [1]


def prime_factors(n):
    out, p = [], 2
    while p * p <= n:
        if n % p == 0:
            out.append(p)
            while n % p == 0:
                n //= p
        p += 1
    if n > 1:
        out.append(n)
    return out


def divisors(n):
    return [d for d in range(1, n + 1) if n % d == 0]


def P_divisors(m):
    """the divisors of m in P = {4} u {odd primes}"""
    out = [p for p in prime_factors(m) if p != 2]
    if m % 4 == 0:
        out.append(4)
    return sorted(out)


def mu_prime(d):
    """(-1)^r if d is a product of r distinct elements of P = {4} u {odd primes}, and 0 otherwise"""
    r, n = 0, d
    if n % 2 == 0:
        if n % 4 or (n // 4) % 2 == 0:
            return 0
        n //= 4
        r += 1
    for p in prime_factors(n):
        if n % (p * p) == 0:
            return 0
        n //= p
        r += 1
    return (-1) ** r


def order(y, m):
    return m // gcd(y, m)


def u(a, m):
    """u(a) in R_m"""
    v = {}
    for y in a:
        y %= m
        assert y, "zero entry"
        v[y] = v.get(y, 0) + 1
    return v


def length(x):
    return sum(x.values())


def add(x, z, k=1):
    out = dict(x)
    for y, c in z.items():
        w = out.get(y, 0) + k * c
        if w:
            out[y] = w
        else:
            out.pop(y, None)
    return out


def scal(k, x):
    return {y: k * c for y, c in x.items()} if k else {}


def in_K(x, m):
    return all(2 * sum(c * ((t * y) % m) for y, c in x.items()) == m * length(x) for t in half_units(m))


def in_B(x, m):
    """Lemma 5.1 (the conditions for t and -t coincide)"""
    return length(x) % 2 == 0 and in_K(x, m)


def is_hodge(a, m):
    """a in B^n_m with n = len(a) - 2 even (Theorem 2.1(iii)); t = 1 gives sum(a) = 0 mod m"""
    return len(a) % 2 == 0 and all(y % m for y in a) and in_B(u(a, m), m)


def inflate(a, q, m):
    """the character (m/q) a of level m (Lemma 2.3(c)): entries (m/q) <a_i>"""
    return tuple((m // q) * (y % q) for y in a)


def standard_characters(m):
    out = []
    for p in prime_factors(m):
        if m == p:
            continue
        d = m // p
        for i in range(1, d):
            if p == 2:
                out.append(((2, i), (i, i + d, m - 2 * i, d)))
            else:
                out.append(((p, i), tuple(i + k * d for k in range(p)) + (m - p * i,)))
    return out


def pair_vectors(m):
    return [u((y, m - y), m) for y in range(1, m // 2 + 1)]


def S_generators(m):
    return pair_vectors(m) + [u(a, m) for _, a in standard_characters(m)]


def nu(x, l, m):
    """Lemma 5.6: the sum mod 2 of the coefficients c_y over the y of order exactly l"""
    return sum(c for y, c in x.items() if order(y, m) == l) % 2


def nu_hypothesis(l, m):
    """l in P = {4} u {odd primes}, l | m and gcd(l, m/l) = 1"""
    in_P = l == 4 or (l > 2 and prime_factors(l) == [l])
    return in_P and m % l == 0 and gcd(l, m // l) == 1


# ====================================================================== lattices (pure Python)
def xgcd(a, b):
    x0, y0, x1, y1 = 1, 0, 0, 1
    while b:
        q = a // b
        a, b = b, a - q * b
        x0, x1 = x1, x0 - q * x1
        y0, y1 = y1, y0 - q * y1
    if a < 0:
        a, x0, y0 = -a, -x0, -y0
    return a, x0, y0


def lin(x, a, y, b):
    """x a + y b for sparse vectors a, b"""
    out = {k: x * v for k, v in a.items()} if x else {}
    if y:
        for k, v in b.items():
            w = out.get(k, 0) + y * v
            if w:
                out[k] = w
            else:
                out.pop(k, None)
    return {k: v for k, v in out.items() if v}


class Echelon:
    """An echelon basis (the pivot of a row is its smallest coordinate with a nonzero entry; pivot entries
    are positive) of the subgroup generated by the inserted vectors.  Only unimodular row operations are
    used, so the rows always generate exactly the subgroup spanned by the inserted vectors."""

    def __init__(self):
        self.rows = {}

    def copy(self):
        e = Echelon()
        e.rows = {j: dict(r) for j, r in self.rows.items()}
        return e

    def insert(self, v):
        v = {k: c for k, c in v.items() if c}
        while v:
            j = min(v)
            if j not in self.rows:
                self.rows[j] = v if v[j] > 0 else {k: -c for k, c in v.items()}
                return
            b = self.rows[j]
            a, c = b[j], v[j]
            if c % a == 0:
                v = lin(1, v, -(c // a), b)
            else:
                g, x, y = xgcd(a, c)                     # g = x a + y c > 0
                self.rows[j] = lin(x, b, y, v)           # new pivot entry g
                v = lin(c // g, b, -(a // g), v)         # (x y; c/g -a/g) has determinant -1

    def contains(self, v):
        v = {k: c for k, c in v.items() if c}
        while v:
            j = min(v)
            if j not in self.rows or v[j] % self.rows[j][j]:
                return False
            v = lin(1, v, -(v[j] // self.rows[j][j]), self.rows[j])
        return True

    def rank(self):
        return len(self.rows)

    def pivot_product(self):
        out = 1
        for j, r in self.rows.items():
            out *= r[j]
        return out

    def rank_mod(self, p):
        """rank of the basis modulo the prime p: the rows whose pivot entry is a unit mod p are independent
        mod p; the others are reduced by them and their residues are eliminated among themselves"""
        good = sorted(j for j, r in self.rows.items() if r[j] % p)
        residues = []
        for j0 in sorted(self.rows):
            if self.rows[j0][j0] % p:
                continue
            v = {k: c % p for k, c in self.rows[j0].items() if c % p}
            for j in good:
                if v.get(j, 0):
                    b = self.rows[j]
                    f = v[j] * pow(b[j], -1, p) % p
                    v = {k: c % p for k, c in lin(1, v, -f, b).items() if c % p}
            residues.append(v)
        return len(good) + rank_mod_p(residues, p)


def rank_mod_p(vectors, p):
    """rank modulo p of a list of sparse vectors (Gaussian elimination)"""
    basis = {}
    for v in vectors:
        v = {k: c % p for k, c in v.items() if c % p}
        while v:
            j = min(v)
            if j not in basis:
                inv = pow(v[j], -1, p)
                basis[j] = {k: c * inv % p for k, c in v.items()}
                break
            v = {k: c % p for k, c in lin(1, v, -v[j], basis[j]).items() if c % p}
    return len(basis)


BIG_PRIME = 2 ** 61 - 1


def rank_K(m):
    """(r_m, number of linear forms, their rank modulo 2^61 - 1); the forms are x -> sum_y c_y (2<ty> - m)"""
    forms = [{y: 2 * ((t * y) % m) - m for y in range(1, m)} for t in half_units(m)]
    return (m - 1) - len(forms), len(forms), rank_mod_p(forms, BIG_PRIME)


def prove_equal_to_B(m, gens):
    """Proves that the subgroup L generated by gens equals B_m (see the docstring).
    Returns (ok, r_m, echelon basis of L, pivot product of L+, primes for which the rank was checked)."""
    ok = all(in_B(g, m) for g in gens)
    r, nforms, rk = rank_K(m)
    ok &= rk == nforms
    E = Echelon()
    for g in gens:
        E.insert(g)
    Ep = E.copy()
    if m % 2 == 0:
        ok &= in_K({m // 2: 1}, m) and not in_B({m // 2: 1}, m) and {m // 2: 2} in gens
        Ep.insert({m // 2: 1})
    ok &= Ep.rank() == r
    D = Ep.pivot_product()
    primes = prime_factors(D)
    ok &= all(Ep.rank_mod(p) == r for p in primes)
    return ok, r, E, D, primes


# ====================================================================== parity homomorphisms on B_m
def f2_solve(equations, nvars):
    """equations: list of (bitmask over nvars variables, right side); returns one solution or None"""
    basis = {}
    for mask, rhs in equations:
        for piv in sorted(basis, reverse=True):
            if (mask >> piv) & 1:
                bm, br = basis[piv]
                mask ^= bm
                rhs ^= br
        if mask == 0:
            if rhs:
                return None
            continue
        piv = mask.bit_length() - 1
        for q in list(basis):
            bm, br = basis[q]
            if (bm >> piv) & 1:
                basis[q] = (bm ^ mask, br ^ rhs)
        basis[piv] = (mask, rhs)
    sol = 0
    for piv, (mask, rhs) in basis.items():
        if rhs:
            sol |= 1 << piv
    return sol


def parity_homomorphism(zero_on, targets, classes):
    """phi(x) = sum_{y in W} c_y + b len(x)/2 mod 2 with W a union of the given disjoint classes, phi = 0 on
    zero_on and phi(x) = e for (x, e) in targets; returns (W, b) or None"""
    nv = len(classes) + 1

    def eq(x):
        mask = 0
        for i, cl in enumerate(classes):
            if sum(c for y, c in x.items() if y in cl) % 2:
                mask |= 1 << i
        if (length(x) // 2) % 2:
            mask |= 1 << (nv - 1)
        return mask

    sol = f2_solve([(eq(x), 0) for x in zero_on] + [(eq(x), e) for x, e in targets], nv)
    if sol is None:
        return None
    W = set()
    for i, cl in enumerate(classes):
        if (sol >> i) & 1:
            W |= set(cl)
    return W, (sol >> (nv - 1)) & 1


def phi_eval(x, W, b):
    return (sum(c for y, c in x.items() if y in W) + b * (length(x) // 2)) % 2


def order_classes(m):
    out = {}
    for y in range(1, m):
        out.setdefault(order(y, m), set()).add(y)
    return [out[k] for k in sorted(out)]


def is_union_of_order_classes(W, m):
    return all({y for y in range(1, m) if order(y, m) == order(z, m)} <= W for z in W)


def describe(W, b, m):
    if is_union_of_order_classes(W, m):
        text = "entries of order " + ", ".join(map(str, sorted({order(y, m) for y in W})))
    else:
        text = "W = the %d residues {%s}" % (len(W), ",".join(map(str, sorted(W))))
    return text + (" + len/2" if b else "")


def f2_rank(rows):
    """rank over F_2 of a list of 0/1 tuples"""
    return rank_mod_p([{i: v for i, v in enumerate(r) if v} for r in rows], 2)


